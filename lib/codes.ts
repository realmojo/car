/** "서울 강남구 …", "전라북도 전주시 …" 같은 주소 앞부분으로 시도를 찾는다 */
export function findSidoByAddress(address: string): Sido | undefined {
  const head = address.trim();
  return SIDO.find(
    (s) =>
      head.startsWith(s.name) ||
      head.startsWith(`${s.short} `) ||
      (SIDO_ALIASES[s.slug] ?? []).some((a) => head.startsWith(a)),
  );
}
