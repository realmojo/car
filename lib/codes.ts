export interface Sigungu {
  /** URL 슬러그로 쓰는 대표 코드 */
  code: string;
  name: string;
  /**
   * 환경공단 API 에 넘길 zscode 목록.
   * 구가 있는 시는 시 코드와 구 코드를, 특별자치도는 신·구 코드를 함께 넣어
   * 데이터가 어느 쪽으로 들어와 있든 빠짐없이 모은다.
   */
  zscodes: string[];
}

type Raw = [code: string, name: string, extra?: string[]];

function build(rows: Raw[], legacyPrefix?: [string, string]): Sigungu[] {
  return rows.map(([code, name, extra = []]) => {
    const codes = [code, ...extra];
    if (legacyPrefix) {
      const [now, old] = legacyPrefix;
      for (const c of [...codes]) {
        if (c.startsWith(now)) codes.push(old + c.slice(2));
      }
    }
    return { code, name, zscodes: codes };
  });
}

