      const vals = g.map((r) => r.num!.combined!);
      const best = [...g].sort((a, b) => b.num!.combined! - a.num!.combined!)[0];
      return [label, `${n(g.length)}개`, `${r1(avg(vals))} km/L`, `${best.name} (${best.num!.combined} km/L)`];
