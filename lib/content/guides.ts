  const eff = [...withEff].sort((a, b) => b.num!.combined! - a.num!.combined!)[0];
  const buckets: Array<[string, (v: number) => boolean]> = [
    ["300km 미만", (v) => v < 300],
    ["300~400km", (v) => v >= 300 && v < 400],
    ["400~500km", (v) => v >= 400 && v < 500],
    ["500km 이상", (v) => v >= 500],
  ];
  const dist = buckets.map(([label, f]) => [label, `${n(withRange.filter((r) => f(r.num!.range!)).length)}개`]);
  const types = new Map<string, number[]>();
