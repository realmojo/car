function base(slug: string, efficiency: Row[]): Article | null {
  switch (slug) {
    case "fuel-economy":
      return fuelEconomy(efficiency);
    case "ev-range":
      return evRange(efficiency);
    case "calculator":
      return calculator();
    case "charger-types":
      return chargerTypes();
    case "car-inspection":
      return carInspection();
    default:
      return null;
  }
}

/** 가이드 본문. 연비·주행거리 가이드는 표시연비 행이 필요하다 */
export function guideArticle(slug: string, efficiency: Row[]): Article | null {
  const a = base(slug, efficiency);
  if (!a) return null;
  const more = EXTRA[slug];
  const related: Block = {
    h2: "함께 보면 좋은 가이드와 데이터",
    p: [
      "차곳간은 한국에너지공단, 한국환경공단, 한국교통안전공단, 한국도로공사와 각 지방자치단체가 공개한 공공데이터로 운전에 필요한 정보를 정리합니다. 아래 가이드와 검색 기능을 함께 활용해 보세요.",
    ],
    links: [
      ...GUIDES.filter((g) => g.slug !== slug).map((g) => ({ label: g.title, href: `/guide/${g.slug}`, note: g.desc })),
      { label: "전기차·수소 충전소 찾기", href: "/charge", note: "충전기 실시간 상태" },
      { label: "자동차 검사소·정비소 찾기", href: "/repair", note: "지역별 목록과 운영 시간" },
    ],
  };
  const blocks = [...a.blocks, ...(more?.blocks ?? []), related];
  return { lead: a.lead, blocks, faq: [...a.faq, ...(more?.faq ?? [])] };
}
